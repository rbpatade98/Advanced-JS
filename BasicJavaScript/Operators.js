let a = 10;
let b = 3;

console.log("a+b =",a + b);   // Addition → 13
console.log("a-b =",a - b);   // Subtraction → 7
console.log("a*b =",a * b);   // Multiplication → 30
console.log("a/b =",a / b);   // Division → 3.33
console.log("a%b =",a % b);   // Modulus → 1
console.log("a**b =",a ** b);  // Exponent → 1000
