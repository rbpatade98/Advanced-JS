// Promise.all()
// waits for all promises to succeed.
// If any promise rejects, it rejects immediately.
// Returns an array of resolved values if all succeed

// Promise.allSettled()
// Waits for all promises to finish, regardless of success or failure

// Promise.race()
// Resolves or rejects as soon as the first promise settles (either success or failure).
// Only the first completed promise matters; the rest are ignored.